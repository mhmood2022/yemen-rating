export function getAuctionBrandOptions(cat: string): YRSelectOption[] {
  const map = AUCTION_BRANDS_BY_CAT[cat];
  if (!map) return withNA(['ماركة معتمدة', 'محلي / يدوي', 'مستورد', 'أخرى']);
  return [...Object.keys(map).map((b) => ({ value: b, label: b })), { value: NOT_AVAILABLE, label: NOT_AVAILABLE }];
}

export function getAuctionModelOptions(cat: string, brand: string): YRSelectOption[] {
  const map = AUCTION_BRANDS_BY_CAT[cat];
  if (!map || !map[brand]) return withNA(['إصدار قياسي', 'نسخة مميزة', 'حسب المعاينة']);
  return withNA(map[brand]);
}

export function parseAuctionMeta(rawDesc: any): {
  notes: string;
  pairs: { label: string; value: string }[];
  videoUrl?: string;
  docImage?: string;
} {
  if (!rawDesc || typeof rawDesc !== 'string') return { notes: '', pairs: [] };
  if (!rawDesc.trim().startsWith('{')) return { notes: rawDesc, pairs: [] };
  try {
    const obj = JSON.parse(rawDesc);
    const pairs = Array.isArray(obj.specs)
      ? obj.specs.filter((x: any) => x?.label && x?.value && x.value !== NOT_AVAILABLE)
      : [];
    return {
      notes: obj.notes || obj.description || '',
      pairs,
      videoUrl: obj.videoUrl || undefined,
      docImage: obj.docImage || undefined,
    };
  } catch {
    return { notes: rawDesc, pairs: [] };
  }
}

